import { constants } from "node:fs";
import { chmod, copyFile, lstat, mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { isDeepStrictEqual } from "node:util";
import { parse, type ParseError } from "jsonc-parser";
import type { Choice } from "./recommend.ts";

export type ProfileArtifact = { readonly name: string; readonly main: Choice; readonly value: unknown };

type Launcher = { readonly path: string; readonly text: string; readonly before: string | null };

export type PreparedProfileArtifacts = {
  readonly binDir: string;
  readonly configPath: string;
  readonly manifestPath: string;
  readonly manifestBefore: string | null;
  readonly manifestText: string;
  readonly launchers: readonly Launcher[];
};

const PROFILE_NAMES = new Set([
  "omo-claude", "omo-gpt", "omo-grok", "omo-glm", "omo-kimi",
  "omo-gemini", "omo-deepseek", "omo-minimax", "omo-qwen",
]);

class ProfileArtifactError extends Error {
  constructor(readonly path: string, detail: string) {
    super(`${path}: ${detail}`);
    this.name = "ProfileArtifactError";
  }
}

function object(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function document(text: string, path: string): Record<string, unknown> {
  const errors: ParseError[] = [];
  const value: unknown = parse(text.trim() ? text : "{}", errors, { allowTrailingComma: true });
  if (errors.length || !object(value)) throw new ProfileArtifactError(path, "expected a valid JSONC object");
  return value;
}

function section(doc: Record<string, unknown>, key: string, path: string): Record<string, unknown> {
  const value = doc[key];
  if (value === undefined) return {};
  if (!object(value)) throw new ProfileArtifactError(path, `${key} must be an object`);
  return value;
}

async function safePath(path: string, directory: boolean): Promise<boolean> {
  try {
    const stat = await lstat(path);
    if (stat.isSymbolicLink() || (directory ? !stat.isDirectory() : !stat.isFile())) {
      throw new ProfileArtifactError(path, "refusing symlink or unexpected file type");
    }
    return true;
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") return false;
    throw error;
  }
}

async function snapshot(path: string): Promise<string | null> {
  return await safePath(path, false) ? readFile(path, "utf8") : null;
}

function quote(text: string): string {
  return `'${text.replaceAll("'", "'\\''")}'`;
}

function launcherSource(profile: ProfileArtifact): string {
  const thinking = profile.main.reasoning;
  return `#!/bin/sh
# Generated by omo-start; ownership is recorded in .omo-start-profiles.json.
export OMO_PROFILE=${quote(profile.name)}
case "\${1-}" in
  ulw-loop|thread|daemon|doctor|setup|install|remove|uninstall|update|list|config|auth|host|schedule|app-server|login|logout|whoami|sync|account|remote)
    exec omo "$@" ;;
  models)
    if [ "\${2-}" = discover ]; then exec omo "$@"; fi ;;
esac
if [ "$#" -eq 1 ]; then
  case "$1" in --version|-v) exec omo "$@" ;; esac
fi
model_override=0
thinking_override=0
skip=0
for arg do
  if [ "$skip" -eq 1 ]; then skip=0; continue; fi
  case "$arg" in
    --) break ;;
    --help|-h) exec omo "$@" ;;
    --model|--provider|--models) model_override=1; skip=1 ;;
    --model=*|--provider=*|--models=*) model_override=1 ;;
    --thinking) thinking_override=1; skip=1 ;;
    --thinking=*) thinking_override=1 ;;
    --mode|--api-key|--system-prompt|--append-system-prompt|--name|-n|--session|--session-id|--spawned-by|--fork|--rebind|--session-dir|--tools|-t|--exclude-tools|-xt|--export|--extension|-e|--skill|--prompt-template|--theme|--use-theme)
      skip=1 ;;
  esac
done
if [ "$model_override" -eq 1 ]; then exec omo "$@"; fi
${thinking ? `if [ "$thinking_override" -eq 0 ]; then
  set -- --thinking ${quote(thinking)} "$@"
fi
` : ""}exec omo --model ${quote(`${profile.main.provider}/${profile.main.model}`)} "$@"
`;
}

/** Preflight only: the caller applies the shared config between prepare and write. */
export async function prepareProfileArtifacts(
  inputPath: string,
  before: string,
  profiles: readonly ProfileArtifact[],
): Promise<PreparedProfileArtifacts> {
  const configPath = resolve(inputPath);
  const home = dirname(configPath);
  const binDir = join(home, "bin");
  const manifestPath = join(home, ".omo-start-profiles.json");
  await safePath(home, true);
  await safePath(configPath, false);
  await safePath(binDir, true);
  const manifestBefore = await snapshot(manifestPath);
  const manifest = document(manifestBefore ?? "{}", manifestPath);
  const oldProfiles = section(manifest, "profiles", manifestPath);
  const oldLaunchers = section(manifest, "launchers", manifestPath);
  const current = section(document(before, configPath), "profiles", configPath);
  // These accumulators intentionally retain entries not included in this apply.
  const nextProfiles = { ...oldProfiles };
  const nextLaunchers = { ...oldLaunchers };
  const launchers: Launcher[] = [];
  const names = new Set<string>();
  for (const profile of profiles) {
    if (!PROFILE_NAMES.has(profile.name) || names.has(profile.name)) {
      throw new ProfileArtifactError(profile.name, "unsupported or duplicate profile name");
    }
    names.add(profile.name);
    if (!object(profile.value)) throw new ProfileArtifactError(profile.name, "profile value must be an object");
    if (Object.hasOwn(current, profile.name)
      && !isDeepStrictEqual(current[profile.name], profile.value)
      && (!Object.hasOwn(oldProfiles, profile.name) || !isDeepStrictEqual(current[profile.name], oldProfiles[profile.name]))) {
      throw new ProfileArtifactError(profile.name, "profile conflicts with unrelated or modified settings");
    }
    const path = join(binDir, profile.name);
    const text = launcherSource(profile);
    const previous = await snapshot(path);
    if (previous !== null && previous !== text
      && (!Object.hasOwn(oldLaunchers, profile.name) || previous !== oldLaunchers[profile.name])) {
      throw new ProfileArtifactError(path, "launcher conflicts with unrelated or modified file");
    }
    nextProfiles[profile.name] = profile.value;
    nextLaunchers[profile.name] = text;
    launchers.push({ path, text, before: previous });
  }
  return {
    binDir, configPath, manifestPath, manifestBefore, launchers,
    manifestText: `${JSON.stringify({ ...manifest, profiles: nextProfiles, launchers: nextLaunchers }, null, 2)}\n`,
  };
}

async function atomicWrite(path: string, before: string | null, text: string, mode: number): Promise<void> {
  if (before === text) {
    await chmod(path, mode);
    return;
  }
  if (before !== null) {
    const backup = `${path}.bak-omo-start-${new Date().toISOString().replace(/[:.]/g, "-")}-${crypto.randomUUID()}`;
    await copyFile(path, backup, constants.COPYFILE_EXCL);
  }
  const tmp = `${path}.${crypto.randomUUID()}.tmp`;
  await writeFile(tmp, text, { mode, flag: "wx" });
  try {
    await chmod(tmp, mode);
    await rename(tmp, path);
  } finally {
    await rm(tmp, { force: true });
  }
}

export async function writeProfileArtifacts(plan: PreparedProfileArtifacts): Promise<readonly string[]> {
  await safePath(dirname(plan.configPath), true);
  await safePath(plan.configPath, false);
  await safePath(plan.binDir, true);
  // Recheck every snapshot before any write; a stale plan must not clobber edits.
  if (await snapshot(plan.manifestPath) !== plan.manifestBefore) {
    throw new ProfileArtifactError(plan.manifestPath, "manifest changed after preparation");
  }
  for (const launcher of plan.launchers) {
    if (await snapshot(launcher.path) !== launcher.before) {
      throw new ProfileArtifactError(launcher.path, "launcher changed after preparation");
    }
  }
  await mkdir(plan.binDir, { recursive: true });
  for (const launcher of plan.launchers) await atomicWrite(launcher.path, launcher.before, launcher.text, 0o755);
  await atomicWrite(plan.manifestPath, plan.manifestBefore, plan.manifestText, 0o600);
  return plan.launchers.map((launcher) => launcher.path);
}
