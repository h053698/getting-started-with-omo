export type Lang = "ko" | "en";

export const LANGS: readonly Lang[] = ["ko", "en"];

export type Localized = { readonly ko: string; readonly en: string };

export const LANG_NAMES: Readonly<Record<Lang, { readonly native: string; readonly gloss: string }>> = {
  ko: { native: "한국어", gloss: "Korean" },
  en: { native: "English", gloss: "영어" },
};

export function same(text: string): Localized {
  return { ko: text, en: text };
}

export function detectLang(env: Readonly<Record<string, string | undefined>> = process.env): Lang {
  const locale = env.LC_ALL || env.LC_MESSAGES || env.LANG || "";
  return locale.toLowerCase().startsWith("ko") ? "ko" : "en";
}

export function padEnd(text: string, width: number): string {
  return text + " ".repeat(Math.max(0, width - Bun.stringWidth(text)));
}

export function truncate(text: string, width: number): string {
  if (Bun.stringWidth(text) <= width) return text;
  let out = "";
  for (const char of text) {
    if (Bun.stringWidth(`${out}${char}…`) > width) break;
    out += char;
  }
  return `${out}…`;
}

